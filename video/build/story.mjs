// Condenses data/engine.json (real engine output, see export_data.py) into the few
// numbers the scenes quote, as window.STORY in data/story.js.
//
//   npm run story

import { readFileSync, writeFileSync } from 'node:fs'

const E = JSON.parse(readFileSync('data/engine.json', 'utf8'))
const r2 = (x) => Math.round(x * 100) / 100

// The laptop story: Sofie buys a EUR 449 laptop on 3 Sep (laptop_story in export_data.py).
const L = E.laptop.states
const laptopDays = Object.entries(L).map(([date, s]) => ({
  date,
  limit: s.today.limit,
  base: s.today.base_limit,
  reduction: s.today.limit_reduction,
  spent: s.today.spent,
  buffer: s.month.buffer,
  debt: s.month.debt,
  health: s.swan.health,
  tier: s.swan.tier,
}))
const buy = L[E.laptop.buy_day]
const bufferBefore = r2(L['2026-09-02'].month.buffer + L['2026-09-02'].today.base_limit - L['2026-09-02'].today.spent)
// Settled days before the purchase, as the buffer grew.
const growth = L[E.laptop.buy_day].history
  .filter((d) => d.date < E.laptop.buy_day)
  .map((d) => ({ date: d.date, limit: d.limit, spent: d.spent, buffer: d.buffer }))

const S = E.sofie_states
const payEve = S['2026-09-24']
const payday = S['2026-09-25']
const m = E.sofie_model
const cases = Object.fromEntries(
  Object.entries(E.cases).map(([k, c]) => {
    const s = c.states['2026-09-30']
    return [
      k,
      {
        name: c.name,
        tagline: c.tagline,
        verdict: c.verdict,
        tier: s.swan.tier,
        generation: s.swan.generation,
        invested: s.rewards.total_invested,
        cycle: s.month.cycle_type,
        target: s.model.target_daily,
        baseline: s.model.baseline_daily,
        affordable: s.model.affordable_daily,
        events: s.events.filter((e) => e.type.startsWith('large_expense')).map((e) => ({ date: e.date, type: e.type, amount: e.amount, message: e.message })),
      },
    ]
  }),
)

const story = {
  laptop: {
    buyDay: E.laptop.buy_day,
    amount: E.laptop.amount,
    bufferBefore,
    covered: r2(Math.min(bufferBefore, E.laptop.amount)),
    debtAfter: buy.month.debt,
    reductionOnBuyDay: buy.today.limit_reduction,
    growth,
    days: laptopDays,
    paydayDebt: L['2026-09-24'].month.debt,
  },
  payday: {
    date: '2026-09-25',
    bufferEve: r2(payEve.month.buffer + payEve.today.limit - payEve.today.spent),
    investedBefore: payEve.rewards.total_invested,
    investedAfter: payday.rewards.total_invested,
    passiveBefore: payEve.rewards.estimated_annual_passive_income,
    passiveAfter: payday.rewards.estimated_annual_passive_income,
    fund: payday.rewards.fund,
    sweeps: payday.rewards.sweeps,
    disclaimer: payday.rewards.disclaimer,
  },
  hero: {
    date: '2026-09-24',
    limit: payEve.today.limit,
    baseline: payEve.model.baseline_daily,
    savingsRate: payEve.model.savings_rate,
    thu: payEve.model.weekday_factors.thu,
  },
  model: {
    profile: m.profile,
    rawWeekday: m.raw_weekday,
    counts: m.counts,
    totals: m.totals,
    income: m.income_total,
    perDay: Object.values(m.history_per_day).map(r2),
    firstDay: Object.keys(m.history_per_day)[0],
    config: m.config,
    oneOffs: m.transactions.filter((t) => t.kind === 'large'),
    fixed: [...new Set(m.transactions.filter((t) => t.kind === 'fixed').map((t) => t.merchant))],
    recurring: [...new Set(m.transactions.filter((t) => t.kind === 'recurring').map((t) => t.merchant))],
    wage: m.transactions.filter((t) => t.kind === 'income').map((t) => ({ merchant: t.merchant, amount: t.amount })),
    p95: (() => {
      const sizes = m.transactions.filter((t) => t.kind === 'discretionary' || t.kind === 'large').map((t) => -t.amount).sort((a, b) => a - b)
      const pos = (sizes.length - 1) * 0.95
      const lo = Math.floor(pos)
      return r2(sizes[lo] + (sizes[Math.min(lo + 1, sizes.length - 1)] - sizes[lo]) * (pos - lo))
    })(),
  },
  cases,
  heroState: {
    today: payEve.today,
    swan: payEve.swan,
    month: { buffer: payEve.month.buffer, days_left: payEve.month.days_left, days_under: payEve.month.days_under, days_over: payEve.month.days_over },
    rewards: { total_invested: payEve.rewards.total_invested, estimated_annual_passive_income: payEve.rewards.estimated_annual_passive_income },
  },
}

writeFileSync('data/story.js', `// Generated by build/story.mjs from data/engine.json. Do not edit.\nwindow.STORY = ${JSON.stringify(story)};\n`)
console.log('story.js', Math.round(JSON.stringify(story).length / 1024), 'KB')
console.log(JSON.stringify({ laptop: { ...story.laptop, days: undefined, growth: story.laptop.growth.length }, payday: story.payday, hero: story.hero, p95: story.model.p95 }, null, 1))
