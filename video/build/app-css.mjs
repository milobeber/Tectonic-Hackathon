// Copies the demo app's real stylesheet (frontend/src/index.css) into the video,
// minus the desktop demo chrome (stage, intro, director panel, gallery) and the
// responsive / reduced-motion media queries. Everything else ships as is.
//
//   npm run app-css

import { readFileSync, writeFileSync } from 'node:fs'

const src = readFileSync('../frontend/src/index.css', 'utf8')

// Split into top-level blocks (selector + balanced braces). Comments are dropped.
const css = src.replace(/\/\*[\s\S]*?\*\//g, '')
const blocks = []
let depth = 0
let start = 0
for (let i = 0; i < css.length; i++) {
  if (css[i] === '{') depth++
  else if (css[i] === '}' && --depth === 0) {
    blocks.push(css.slice(start, i + 1).trim())
    start = i + 1
  }
}

const DROP = [
  /^@media/,
  /^html\s*,\s*body/,
  /(^|[\s,])\.(stage|intro|director|gallery|dc-|linkish|dot\b|dot--)/,
]
const kept = blocks.filter((b) => {
  const selector = b.slice(0, b.indexOf('{')).trim()
  return !DROP.some((re) => re.test(selector))
})

const header = `/* Generated by build/app-css.mjs from frontend/src/index.css. Do not edit. */\n`
writeFileSync('assets/app.css', header + kept.join('\n') + '\n')
console.log(`app.css: kept ${kept.length} of ${blocks.length} blocks`)
